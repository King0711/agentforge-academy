"""Generate supabase/vibecoding-class-guides.sql from guides.py.

    python scripts/vibe-class-guides/build.py

The guides live in a table keyed by class number (1-8), not on live_sessions
rows, so every future cohort gets them without anyone copying content across.
"""
import json
import pathlib
import re

from guides import GUIDES

OUT = pathlib.Path(__file__).resolve().parents[2] / "supabase" / "vibecoding-class-guides.sql"

HEADER = """-- Vibe Coding Bootcamp: student-facing guide for each of the 8 classes
-- (agenda, key ideas, prompts, reference code, working-result checklist,
-- troubleshooting, stretch goals, assignment).
--
-- GENERATED by scripts/vibe-class-guides/build.py from guides.py. Edit
-- guides.py and regenerate; do not edit this file by hand.
--
-- Keyed by class number, not by live_sessions row, so a new cohort needs no
-- copying. Same paywall as vibecoding_prompts: an active Vibe Coding
-- entitlement or an admin. The table is only ever written by this migration
-- (service role / postgres), so there is no insert/update policy.

create table if not exists public.vibecoding_class_guides (
  class_number integer primary key check (class_number between 1 and 8),
  guide jsonb not null,
  updated_at timestamptz not null default now()
);

alter table public.vibecoding_class_guides enable row level security;

drop policy if exists "Vibe Coding class guides require active entitlement or admin"
  on public.vibecoding_class_guides;
create policy "Vibe Coding class guides require active entitlement or admin"
  on public.vibecoding_class_guides for select
  using (
    exists (select 1 from entitlements e where e.user_id = auth.uid() and e.is_admin = true)
    or exists (
      select 1 from entitlements e
      where e.user_id = auth.uid()
        and e.vibecoding_expires_at is not null
        and e.vibecoding_expires_at > now()
    )
  );

revoke all on public.vibecoding_class_guides from anon;
revoke all on public.vibecoding_class_guides from authenticated;
grant select on public.vibecoding_class_guides to authenticated;

"""

FOOTER = """
do $$
begin
  if (select count(*) from public.vibecoding_class_guides) <> 8 then
    raise exception 'expected 8 class guides, found %', (select count(*) from public.vibecoding_class_guides);
  end if;
end $$;
"""


def main():
    assert sorted(GUIDES) == list(range(1, 9)), "need exactly classes 1-8"
    parts = [HEADER]
    for n in sorted(GUIDES):
        body = json.dumps(GUIDES[n], ensure_ascii=False, indent=1)
        assert "$guide$" not in body
        parts.append(
            f"insert into public.vibecoding_class_guides (class_number, guide)\n"
            f"values ({n}, $guide${body}$guide$::jsonb)\n"
            f"on conflict (class_number) do update\n"
            f"  set guide = excluded.guide, updated_at = now();\n\n"
        )
    parts.append(FOOTER)
    OUT.write_text("".join(parts), encoding="utf-8")
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
